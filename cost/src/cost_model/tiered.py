"""cost-tiered: Elasticsearch tiered setups vs Cartridge for the five real datasets, 10 TB/day, 30 days, via matrix.price_row (no new formulas).

Writes results/cost/tiered-10tb-30d.{md,json}.
"""
import json

import typer

from .load import COST_DIR, REPO_ROOT, load_inputs
from .matrix import DATASETS, price_row
from .model import build_params, system_totals

S = COST_DIR / "scenarios"
OUT = REPO_ROOT / "results" / "cost"
ENT_GAIN = 2.87 / 3.83  # Elastic's published figures: Enterprise logsdb (2.87) retains this share of free-licence logsdb (3.83)
ELASTIC_76 = 39.4 / 162.7  # Elastic's published logsdb result (model coefficient logsdb_enterprise_retained_fraction)
HTTP_MODEL_STD = 18_656_019_625  # http_logs: the cost model's default Elasticsearch size (hot restore), used by the tiered figures
KEYS = ["http_logs", "CloudTrail", "Alibaba", "Thunderbird", "CockroachDB"]
LOGSDB_ROW = {"CloudTrail": "ES stock logs data stream"}  # stock logsdb stream
allhot, hf, hw = (load_inputs(S / f"10tb-30d{v}.yaml") for v in ("", "-hotfrozen", "-hotwarm"))
P = {k: build_params(i) for k, i in (("hot", allhot), ("hf", hf), ("hw", hw))}


def find(d, pred):
    return next(r for r in d["rows"] if pred(r[0]))


def serverless() -> float:
    return system_totals(allhot, P["hot"], ["elastic_serverless"])["elastic_serverless"]


def dataset(key: str) -> dict:
    name, d = next((n, d) for n, d in DATASETS.items() if n.startswith(key) or key in n)
    raw = d["raw"]
    std = (HTTP_MODEL_STD if key == "http_logs" else d["standard"]) / raw
    cart = max((r for r in d["rows"] if r[1].startswith("cart")), key=lambda r: r[2])
    os_ = find(d, lambda c: c.startswith("OpenSearch 3.9"))
    ldb = find(d, lambda c: ("logsdb" in c or "logs data stream" in c or "OTel trace stream" in c) and "Enterprise" not in c and "flattened" not in c) if key not in LOGSDB_ROW else find(d, lambda c: LOGSDB_ROW[key] in c)
    ent = next((r for r in d["rows"] if r[1] == "es_ent"), None)
    ent_ratio, ent_note = (ent[2] / raw, "measured") if ent else (ldb[2] / raw * ENT_GAIN, "DERIVED: free-logsdb bytes x 2.87/3.83")
    R = lambda r: r[2] / raw
    rows = [
        ("OpenSearch 3.9 default, all hot", price_row(allhot, P["hot"], "es", R(os_), std), "measured"),
        ("ES standard, all hot", price_row(allhot, P["hot"], "es", std, std), "http_logs: model default size" if key == "http_logs" else "measured"),
        ("ES logsdb (free), all hot", price_row(allhot, P["hot"], "es", R(ldb), std), "measured"),
        ("ES hot/warm, free licence", price_row(hw, P["hw"], "es", std, std), "ES standard size"),
        ("ES hot/frozen, Enterprise", price_row(hf, P["hf"], "es", std, std), "ES standard size"),
        ("ES hot/frozen + logsdb, Enterprise (our logsdb size)", price_row(hf, P["hf"], "es_ent", ent_ratio, std), ent_note),
        ("ES hot/frozen + logsdb, Enterprise (Elastic's published 76% on ES standard size)", price_row(hf, P["hf"], "es_ent", std * ELASTIC_76, std), "Elastic-published 76% factor"),
        ("Elastic Serverless (list)", serverless(), "billed on ingested GB: independent of stored size"),
    ]
    c = price_row(allhot, P["hot"], cart[1], R(cart), std)
    es = [r for r in rows if r[0].startswith("ES") or r[0].startswith("Elastic")]
    best = min(es, key=lambda r: r[1])
    return {"dataset": name, "cartridge_cfg": cart[0], "cartridge_usd": c, "setups": [{"setup": s, "usd_year": u, "x_vs_cart": u / c, "basis": b} for s, u, b in rows],
            "cheapest_es": {"setup": best[0], "usd_year": best[1], "x_vs_cart": best[1] / c}}


def md(res):
    o = ["# Elasticsearch tiered setups vs Cartridge, 10 TB/day, 30 days searchable\n", "Estimate only: the cost model as a calculator (matrix.price_row / system_totals; generated by `uv run cost-tiered`). "
         "Serverless is billed on ingested/retained GB, so it is the same $ for every dataset. Compute coefficients stay the http_logs measurements. \"Cartridge\" is the larger of the two measured Cartridge outputs per dataset.\n"]
    for r in res:
        o += [f"\n## {r['dataset']}\n", f"Cartridge: {r['cartridge_cfg']} = ${r['cartridge_usd']:,.0f}/yr\n", "| setup | $/yr | x vs Cartridge | size basis |", "|---|---|---|---|"]
        o += [f"| {s['setup']} | ${s['usd_year']:,.0f} | {s['x_vs_cart']:.1f}x | {s['basis']} |" for s in r["setups"]]
    o += ["\n## Summary: cheapest Elasticsearch setup\n", "| dataset | cheapest setup | $/yr | x vs Cartridge |", "|---|---|---|---|"]
    o += [f"| {r['dataset']} | {r['cheapest_es']['setup']} | ${r['cheapest_es']['usd_year']:,.0f} | {r['cheapest_es']['x_vs_cart']:.1f}x |" for r in res]
    return "\n".join(o) + "\n"


def main() -> None:
    res = [dataset(k) for k in KEYS]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tiered-10tb-30d.json").write_text(json.dumps(res, indent=1) + "\n")
    (OUT / "tiered-10tb-30d.md").write_text(md(res))
    print(md(res))


def cli() -> None:
    typer.run(main)
