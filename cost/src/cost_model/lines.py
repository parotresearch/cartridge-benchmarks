"""cost-lines SCENARIO.yaml: every priced line item (quantity, unit price, formula) for each system in one scenario, as markdown.

Uses the scenario's own coefficients (the http_logs measurements), so it shows the model's sizing arithmetic for the http_logs row.
Writes results/cost/lines-<scenario>.md.
"""

from pathlib import Path
from typing import Annotated

import typer

from .load import REPO_ROOT, load_inputs
from .model import line_items


def to_markdown(scenario: Path) -> tuple[str, str]:
    inputs = load_inputs(scenario)
    items = line_items(inputs)
    out = [f"# Line items: {inputs.scenario.label}\n", "Coefficients are the http_logs measurements. Generated by `uv run cost-lines`.\n"]
    for system, g in items.groupby("system", sort=False):
        out += [f"\n## {system}: ${g.usd_year.sum():,.0f}/yr\n", "| component | tier | $/yr | formula |", "|---|---|---|---|"]
        out += [f"| {r.component} | {r.tier} | ${r.usd_year:,.0f} | {r.formula} |" for r in g.itertuples()]
    return inputs.scenario.name, "\n".join(out) + "\n"


def main(scenario: Annotated[Path, typer.Argument(exists=True, dir_okay=False)]) -> None:
    name, md = to_markdown(scenario)
    out = REPO_ROOT / "results" / "cost"
    out.mkdir(parents=True, exist_ok=True)
    (out / f"lines-{name}.md").write_text(md)
    typer.echo(f"wrote {out / f'lines-{name}.md'}")


def cli() -> None:
    typer.run(main)
